using Printf

"C1 transition from zero to one over a unit interval."
smooth(t) = (q = clamp(t, 0.0, 1.0); q*q*(3 - 2q))

"Write an LDFI grip grid with 20-character fields and 80-character records."
function write_grip(name, grip, u, v)
    open(joinpath(@__DIR__, name * "_mu.crg"), "w") do io
        println(io, "\$CT\nDimensionless tire grip multiplier, not elevation.")
        println(io, "Generated by assets/roads/generate.jl; quadratic nodal interpolation.")
        println(io, name == "ice_patch" ? "Patch x=455..495 m; 4 m edge blends." :
            name == "right_patch" ? "Patch x=446..466 m; 4 m longitudinal blends; 2 m lateral blend." : "Uniform grip; edge holding outside grid.")
        println(io, "\$!\n\$ROAD_CRG")
        println(io, "REFERENCE_LINE_START_U = $(first(u))\nREFERENCE_LINE_END_U = $(last(u))")
        println(io, "REFERENCE_LINE_INCREMENT = $(step(u))")
        println(io, "REFERENCE_LINE_START_X = $(first(u))\nREFERENCE_LINE_START_Y = 0")
        println(io, "REFERENCE_LINE_START_PHI = 0\n\$!\n\$KD_DEFINITION\n#:LDFI")
        for y in v
            println(io, "D:long section at v = $y,m")
        end
        println(io, "\$!\n\$\$\$\$")
        for x in u
            values = [grip(x, y) for y in v]
            for first in 1:4:length(values)
                println(io, join(@sprintf("%20.12E", a) for a in values[first:min(first+3,end)]))
            end
        end
    end
end

"Longitudinal extent of the one-sided patch in the hard-stop brake phase, with four-meter edge blends."
patch(x) = smooth((x - 446) / 4) * smooth((466 - x) / 4)
write_grip("uniform", (x,y) -> 1.0, 0.0:1.0:2.0, -1.0:1.0:1.0)
write_grip("uniform_low", (x,y) -> 0.3, 0.0:1.0:2.0, -1.0:1.0:1.0)
write_grip("ice_patch", (x,y) -> 1 - 0.7smooth((x-455)/4)*smooth((495-x)/4), 420.0:0.5:530.0, -1.0:1.0:1.0)
write_grip("right_patch", (x,y) -> 1 - 0.7patch(x)*smooth((1-y)/2), 430.0:1.0:480.0, -5.0:0.25:5.0)


"Write a height grid, optionally carrying a constant reference-line slope channel."
function write_height(name, height, u, v; phi = 0.0, slope = nothing, offset_y = 0.0)
    open(joinpath(@__DIR__, name * "_z.crg"), "w") do io
        println(io, "\$CT\nRoad elevation in meters.\nGenerated by assets/roads/generate.jl.\n\$!\n\$ROAD_CRG")
        println(io, "REFERENCE_LINE_START_U = $(first(u))\nREFERENCE_LINE_END_U = $(last(u))")
        println(io, "REFERENCE_LINE_INCREMENT = $(step(u))")
        println(io, "REFERENCE_LINE_START_X = $(first(u)*cos(phi))\nREFERENCE_LINE_START_Y = $(first(u)*sin(phi) + offset_y)")
        println(io, "REFERENCE_LINE_START_PHI = $phi\n\$!\n\$KD_DEFINITION\n#:LDFI")
        slope === nothing || println(io, "D:reference line slope,m/m")
        for y in v
            println(io, "D:long section at v = $y,m")
        end
        println(io, "\$!\n\$\$\$\$")
        for x in u
            values = [height(x,y) for y in v]
            slope === nothing || pushfirst!(values, slope)
            for first in 1:4:length(values)
                println(io, join(@sprintf("%20.12E", a) for a in values[first:min(first+3,end)]))
            end
        end
    end
end

"Raised cosine hill on x=240..400 m, with peak grade 0.08."
hill(x) = 240 <= x <= 400 ? (0.08 * 160 / (2pi)) * (1 - cos(2pi*(x-240)/160)) : 0.0
write_height("flat", (x,y) -> 0.0, 0.0:1.0:2.0, -1.0:1.0:1.0)
write_height("hill", (x,y) -> hill(x), 220.0:1.0:420.0, -1.0:1.0:1.0)
write_height("hill_across", (x,y) -> hill(x), 220.0:1.0:420.0, -600.0:600.0:600.0; phi = pi/2, offset_y = -280.0)
write_height("ramp", (x,y) -> 0.0, 0.0:250.0:500.0, -1.0:1.0:1.0; slope = 0.02)
# The car starts at the origin, so its parked-on-a-grade ramp extends behind it.
write_height("ramp_hold", (x,y) -> 0.0, -250.0:250.0:250.0, -1.0:1.0:1.0; slope = 0.02)
